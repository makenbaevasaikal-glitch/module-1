# Создайте функцию, которая принимает на вход два целых числа в виде строки и выдает их сумму (также в виде строки):

# Пример: ( Вход1, Вход2 -->Выход )

# "4",  "5" --> "9"
# "34", "5" --> "39"
# "", "" --> "0"
# "2", "" --> "2"
# "-5", "3" --> "-2"
# Примечания:

# Если какой-либо из входных данных является пустой строкой, считайте его равным нулю.

# Входные данные и ожидаемый выходной сигнал никогда не превысят лимит знакового 32-битного целого числа ( 2^31 - 1).

def sum_str(a, b):
    num_a = int(a) if a else 0
    num_b = int(b) if b else 0
    return str(num_a + num_b)
print(sum_str("48", "6")) 