# Джеку очень нравится число пять: хитрость в том, что каждое число нужно умножить на 5 в степени, равной количеству цифр каждого числа, например:

#   3 -->    15  (  3 * 5¹)
#  10 -->   250  ( 10 * 5²)
# 200 --> 25000  (200 * 5³)
#   0 -->     0  (  0 * 5¹)
#  -3 -->   -15  ( -3 * 5¹)

def multiply(n):
    digits_count = len(str(abs(n)))
    
    return n * (5 ** digits_count)
print(multiply(10))