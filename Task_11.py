# На экране вашего телефона индикатор заряда батареи отображается в виде ряда из 5 полосок . Каждая полная полоска соответствует 20% заряда. Полоса загорается только тогда, когда достигнут полный уровень заряда в 20%.

# Напишите функцию battery_bars(percent), которая возвращает значение заряда батареи в виде строки: #для горящей полоски — .значение для пустой, все значения заключены в квадратные скобки.

# Примеры
# battery_bars(100)  # => "[#####]"
# battery_bars(70)   # => "[###..]"
# battery_bars(20)   # => "[#....]"
# battery_bars(19)   # => "[.....]"
# battery_bars(0)    # => "[.....]"

def battery_bars(percent):
    full_bars = percent // 20
    empty_bars = 5 - full_bars
    return "[" + ("#" * full_bars) + ("." * empty_bars) + "]"
print(battery_bars(99))