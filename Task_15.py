# Введение
# Первый век охватывает период с 1-го года до 100-го года включительно , второй век — с 101-го года до 200-го года включительно и так далее.

# Задание
# Если известен год, верните название столетия, в котором он находится.

# Примеры
# 1705 --> 18
# 1900 --> 19
# 1601 --> 17
# 2000 --> 20
# 2742 --> 28

def century(year):
    return (year - 1) // 100 + 1
print(century(1922))