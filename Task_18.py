# Дополните функцию суммы квадратов так, чтобы она возводила в квадрат каждое переданное ей число, а затем суммировала результаты.

# Например, [1, 2, 2]оно должно вернуть значение 9, потому что
# 1^2 + 2^2 + 2^2 = 9.

def square_sum(numbers):
    total = 0  
    for num in numbers:
        total += num ** 2  
    return total

print(square_sum([1, 2, 3]))
