# Часы показывают hчасы, mминуты и sсекунды после полуночи.

# Ваша задача — написать функцию, которая возвращает время, прошедшее с полуночи, в миллисекундах.

# Пример:
# h = 0
# m = 1
# s = 1

# result = 61000

def past(h, m, s):
    total_seconds = (h * 3600) + (m * 60) + s
    return total_seconds * 1000
print(past(1, 1, 1))