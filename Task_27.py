# Удалите восклицательный знак из конца строки. Для начинающих можно предположить, что входные данные всегда являются строкой, проверять это не нужно.

# Примеры
# "Hi!"     ---> "Hi"
# "Hi!!!"   ---> "Hi!!"
# "!Hi"     ---> "!Hi"
# "!Hi!"    ---> "!Hi"
# "Hi! Hi!" ---> "Hi! Hi"
# "Hi"      ---> "Hi"

def remove(s):
    if s.endswith("!"):
        return s[:-1] 
    else:
        return s    
print(remove("Hi! Hi!"))