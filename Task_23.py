# Ваши одноклассники попросили вас переписать для них некоторые документы. Вы знаете, что одноклассников 'n', а документов 'm'.

# Ваша задача — рассчитать, сколько пустых страниц вам нужно. Если n < 0или m < 0вернет 0.

# Пример:
# n= 5, m=5: 25
# n=-5, m=5:  0

def paperwork(n, m):
    if n < 0 or m < 0:
        return 0
    else:
        return n * m
print(paperwork(5, 5))  